/// Maximum lines preserved in the circular scrollback history buffer.


impl FramebufferConsole {
    pub(crate) fn put_pixel(&self, x: usize, y: usize, color: u32) {
        if self.fb_addr == 0 || x >= self.width || y >= self.height {
            return;
        }
        let offset = y * self.pitch_pixels + x;
        // SAFETY: `fb_addr` points to the Limine-mapped 32-bpp linear framebuffer in HHDM
        // and `(x, y)` is bounds-checked against `(width, height)`.
        unsafe {
            let ptr = (self.fb_addr as *mut u32).add(offset);
            core::ptr::write_volatile(ptr, color);
        }
    }

    pub(crate) fn fill_rect(&self, x0: usize, y0: usize, w: usize, h: usize, color: u32) {
        if self.fb_addr == 0 {
            return;
        }
        let x_end = (x0 + w).min(self.width);
        let y_end = (y0 + h).min(self.height);
        for y in y0..y_end {
            let row_base = y * self.pitch_pixels;
            for x in x0..x_end {
                // SAFETY: Bounds-checked within `(width, height)`.
                unsafe {
                    let ptr = (self.fb_addr as *mut u32).add(row_base + x);
                    core::ptr::write_volatile(ptr, color);
                }
            }
        }
    }

    pub(crate) fn draw_glyph_scaled(
        &self,
        ch: u8,
        px_x: usize,
        px_y: usize,
        fg: u32,
        bg: Option<u32>,
        scale: usize,
    ) {
        let idx = if (0x20..=0x7E).contains(&ch) {
            (ch - 0x20) as usize
        } else {
            (b'?' - 0x20) as usize
        };
        let glyph = &FONT_8X8[idx];

        for (gy, &row_bits) in glyph.iter().enumerate() {
            for gx in 0..8 {
                let bit_set = (row_bits & (0x80 >> gx)) != 0;
                if bit_set {
                    for sy in 0..scale {
                        for sx in 0..scale {
                            self.put_pixel(px_x + gx * scale + sx, px_y + gy * scale + sy, fg);
                        }
                    }
                } else if let Some(bg_col) = bg {
                    for sy in 0..scale {
                        for sx in 0..scale {
                            self.put_pixel(px_x + gx * scale + sx, px_y + gy * scale + sy, bg_col);
                        }
                    }
                }
            }
        }
    }

    pub(crate) fn draw_str_at(&self, text: &str, mut x: usize, y: usize, fg: u32, scale: usize) {
        for b in text.bytes() {
            self.draw_glyph_scaled(b, x, y, fg, None, scale);
            x += 8 * scale;
        }
    }

    /// Paints the top visual FipSOs header bar on the linear framebuffer.
    pub(crate) fn draw_header_banner(&self) {
        self.fill_rect(0, 0, self.width, HEADER_HEIGHT - 2, COLOR_HEADER_BG);
        self.fill_rect(0, HEADER_HEIGHT - 2, self.width, 2, COLOR_HEADER_BORDER);

        let title = "FipSOs v3.1 Framekernel (x86_64 SMP | Multi-USB xHCI/EHCI/OHCI | DHCP | TCP Remote :2222)";
        if self.width >= 1200 {
            self.draw_str_at(title, TEXT_LEFT_X, 16, COLOR_HEADER_TITLE, 2);
        } else {
            self.draw_str_at(title, TEXT_LEFT_X, 18, COLOR_HEADER_TITLE, 1);
        }
    }


    pub(crate) fn scroll_up_one_line(&self) {
        if self.fb_addr == 0 || self.max_rows == 0 {
            return;
        }
        if let Some(mut overlay) = MOUSE_OVERLAY.try_lock() {
            if overlay.has_prev {
                for dy in 0..CURSOR_SIZE {
                    let py = overlay.prev_y + dy;
                    if py < self.height {
                        for dx in 0..CURSOR_SIZE {
                            let px = overlay.prev_x + dx;
                            if px < self.width {
                                self.put_pixel(px, py, overlay.saved_patch[dy * CURSOR_SIZE + dx]);
                            }
                        }
                    }
                }
                overlay.has_prev = false;
            }
        }
        let text_area_height = self.max_rows * LINE_HEIGHT;
        let copy_rows = text_area_height.saturating_sub(LINE_HEIGHT);

        for y in 0..copy_rows {
            let dst_y = TEXT_TOP_Y + y;
            let src_y = dst_y + LINE_HEIGHT;
            let dst_base = dst_y * self.pitch_pixels;
            let src_base = src_y * self.pitch_pixels;
            // Preserve the top-right Zero-Copy graphical widget overlay (x >= 1076, y <= 170)
            let row_width = if src_y <= 170 {
                self.width.min(1076)
            } else {
                self.width
            };
            // SAFETY: `dst_base` and `src_base + row_width` are strictly within the mapped framebuffer bounds.
            unsafe {
                let base_ptr = self.fb_addr as *mut u32;
                core::ptr::copy(base_ptr.add(src_base), base_ptr.add(dst_base), row_width);
            }
        }

        let clear_y = TEXT_TOP_Y + copy_rows;
        self.fill_rect(0, clear_y, self.width, LINE_HEIGHT, BOOT_FB_COLOR_RGB);
    }


    pub fn redraw_view(&mut self) {
        if self.fb_addr == 0 || self.max_rows == 0 {
            return;
        }
        let text_area_h = self.max_rows * LINE_HEIGHT;
        self.fill_rect(0, TEXT_TOP_Y, self.width, text_area_h, BOOT_FB_COLOR_RGB);

        let total = self.history_total + (if self.current_line.len > 0 || self.cursor_col > 0 { 1 } else { 0 });
        let max_scroll = total.saturating_sub(self.max_rows);
        let eff_scroll = self.scroll_offset.min(max_scroll);

        let end_idx = total.saturating_sub(eff_scroll);
        let start_idx = end_idx.saturating_sub(self.max_rows);
        let rows_to_draw = end_idx - start_idx;

        for r in 0..rows_to_draw {
            let line_idx = start_idx + r;
            let line = if line_idx == self.history_total {
                &self.current_line
            } else {
                let slot = line_idx % SCROLLBACK_LINES;
                &self.history[slot]
            };

            let py = TEXT_TOP_Y + r * LINE_HEIGHT;
            for c in 0..line.len.min(self.max_cols) {
                let cell = line.cells[c];
                if cell.ch >= 0x20 && cell.ch <= 0x7E && cell.ch != b' ' {
                    let px = TEXT_LEFT_X + c * CHAR_WIDTH;
                    self.draw_glyph_scaled(cell.ch, px, py, cell.fg, Some(BOOT_FB_COLOR_RGB), 1);
                }
            }
        }

        if self.scroll_offset > 0 {
            let badge = "[HISTORIAL: RePag / AvPag]";
            let bx = self.width.saturating_sub(260);
            self.draw_str_at(badge, bx, HEADER_HEIGHT + 6, 0x00FF_D166, 1);
        }
    }


    pub(crate) fn present_rect(&self, src_bytes: &[u8], x: usize, y: usize, width: usize, height: usize) {
        if self.fb_addr == 0 || width == 0 || height == 0 {
            return;
        }

        // Draw a 2px neon frame and title around the Zero-Copy widget in the upper-right corner
        let border_x = x.saturating_sub(2);
        let border_y = y.saturating_sub(14);
        self.fill_rect(border_x, border_y, width + 4, height + 16, COLOR_HEADER_BG);
        self.fill_rect(border_x, border_y, width + 4, 1, COLOR_HEADER_BORDER);
        self.fill_rect(
            border_x,
            y + height + 1,
            width + 4,
            1,
            COLOR_HEADER_BORDER,
        );
        self.fill_rect(border_x, border_y, 1, height + 16, COLOR_HEADER_BORDER);
        self.fill_rect(
            x + width + 1,
            border_y,
            1,
            height + 16,
            COLOR_HEADER_BORDER,
        );
        self.draw_str_at(
            "ZERO-COPY /dev/fb0",
            x + 4,
            y.saturating_sub(11),
            COLOR_HEADER_TITLE,
            1,
        );

        for dy in 0..height {
            let py = y + dy;
            if py >= self.height {
                break;
            }
            for dx in 0..width {
                let px = x + dx;
                if px >= self.width {
                    break;
                }
                let byte_idx = (dy * width + dx) * 4;
                if byte_idx + 4 <= src_bytes.len() {
                    let pixel = u32::from_le_bytes([
                        src_bytes[byte_idx],
                        src_bytes[byte_idx + 1],
                        src_bytes[byte_idx + 2],
                        src_bytes[byte_idx + 3],
                    ]);
                    self.put_pixel(px, py, pixel);
                }
            }
        }
    }
}
